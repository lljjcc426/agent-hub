"""Exercise the slash commands using examples/chat-acceptance.ts in workflow mode."""
import json
import sys
from pathlib import Path

from playwright.sync_api import expect, sync_playwright


info = json.loads((Path(sys.argv[1]) / "browser.json").read_text())
name, value = info["cookie"].split("=", 1)

with sync_playwright() as pw:
    browser = pw.chromium.launch(channel="msedge", headless=True)
    for width in (1440, 390):
        context = browser.new_context(viewport={"width": width, "height": 900})
        context.add_init_script("localStorage.setItem('agenthub.configuration.language','en')")
        context.add_cookies([{"name": name, "value": value, "url": info["base"]}])
        page = context.new_page()
        errors = []
        page.on("pageerror", lambda error: errors.append(str(error)))
        page.goto(info["url"])
        box = page.locator(".composer-input")
        expect(box).to_be_visible()
        if width == 1440:
            box.fill("/plan")
            expect(page.get_by_role("option", name="Plan before executing /plan")).to_be_visible()
            box.press("Enter")
            expect(page.get_by_role("button", name="Remove plan mode")).to_be_visible()
            box.fill("Prepare the approved report")
            box.press("Enter")
            first = page.get_by_role("region", name="Who will read the report?")
            expect(first).to_be_visible(timeout=15000)
            expect(page.get_by_role("button", name="Confirm and run")).to_have_count(0)
            first.get_by_role("radio", name="Leadership").check()
            first.get_by_role("button", name="Confirm selection").click()
            second = page.get_by_role("region", name="What format should the report use?")
            expect(second).to_be_visible()
            expect(page.get_by_role("button", name="Confirm and run")).to_have_count(0)
            box.fill("Table")
            box.press("Enter")
            expect(page.get_by_role("heading", name="Detailed report")).to_be_visible()
            expect(page.get_by_text("Approved work started.", exact=True)).to_have_count(0)
            page.get_by_role("button", name="Revise plan").click()
            expect(box).to_be_focused()
            box.fill("Use a shorter version")
            box.press("Enter")
            expect(page.get_by_role("heading", name="Short report")).to_be_visible()
            page.reload()
            current = page.get_by_role("region", name="Proposed plan").filter(has_text="Short report")
            expect(current.get_by_role("button", name="Confirm and run")).to_be_visible()
            expect(page.get_by_role("button", name="Confirm and run")).to_have_count(1)
            box.fill("A draft revision in another window")
            second_window = browser.new_context()
            second_window.add_init_script("localStorage.setItem('agenthub.configuration.language','en')")
            second_window.add_cookies([{"name": name, "value": value, "url": info["base"]}])
            other_page = second_window.new_page()
            other_page.goto(info["url"])
            other_page.get_by_role("button", name="Confirm and run").click()
            expect(page.get_by_text("Approved report evidence", exact=True).first).to_be_visible(timeout=20000)
            expect(current.get_by_role("button", name="Confirm and run")).to_have_count(0)
            box.press("Enter")
            expect(page.get_by_text("This plan has closed. Your draft was kept.")).to_be_visible()
            second_window.close()
        box.fill("/ref")
        box.press("Enter")
        search = page.get_by_role("textbox", name="Search messages in this conversation")
        expect(search).to_be_focused()
        search.fill("Approved report evidence")
        result = page.get_by_role("menuitem", name="Research Approved report evidence")
        expect(result).to_be_visible()
        search.press("ArrowDown")
        expect(result).to_be_focused()
        result.press("Enter")
        expect(page.locator(".composer-quote")).to_contain_text("Approved report evidence")
        expect(box).to_be_focused()
        page.get_by_role("button", name="Cancel quote").click()
        box.fill("/context")
        box.press("Enter")
        page.get_by_role("button", name="View usage details").click()
        panel = page.get_by_role("region", name="Context usage")
        agent = panel.get_by_role("combobox", name="Agent")
        expect(agent).to_be_visible()
        agent.select_option(label="Research")
        meter = panel.get_by_role("meter")
        expect(meter).to_have_attribute("aria-valuenow", "512")
        expect(meter).to_have_attribute("aria-valuemax", "4096")
        expect(meter).to_have_attribute("aria-valuetext", "12.5%")
        agent.select_option(label="Router")
        expect(panel.get_by_role("region", name="Model window")).to_be_visible()
        assert not errors, errors
        context.close()
    browser.close()

print("PASS: two planning questions, revision and reload, confirmed Worker dispatch, reference search and Worker context at 1440px and 390px")
